# Storing some basic details about the student
student_name = "Aasi Mishra"
student_age = 24
student_height = 165
student_status = True

# Displaying each value along with its data type
print("Student Name:", student_name, "| Type:", type(student_name))
print("Age:", student_age, "| Type:", type(student_age))
print("Height:", student_height, "cm | Type:", type(student_height))
print("Student Status:", student_status, "| Type:", type(student_status))

# Expected Output:
# Student Name: Aasi Mishra | Type: <class 'str'>
# Age: 24 | Type: <class 'int'>
# Height: 165 cm | Type: <class 'int'>
# Student Status: True | Type: <class 'bool'>
