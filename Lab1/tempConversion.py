# 4. Celsius to Fahrenheit

# Taking Celsius temperature from the user
celsius_value = float(input("Enter Celsius temperature: "))

# Applying the conversion formula
fahrenheit_value = (celsius_value * 9 / 5) + 32

print("\nTemperature Conversion")
print("Celsius    :", celsius_value, "°C")
print("Fahrenheit :", fahrenheit_value, "°F")

# Sample Output:
# Enter Celsius temperature: 25
#
# Temperature Conversion
# Celsius    : 25.0 °C
# Fahrenheit : 77.0 °F
